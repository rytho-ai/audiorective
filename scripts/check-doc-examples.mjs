/** The ts/js blocks, their page's import preferences, and explicit fence metadata. */
export function exampleBlocks(file, text) {
  const blocks = fencedBlocks(text).filter((b) => LANGS.has(b.lang));
  const pageImports = blocks.flatMap((b) => {
    const source = ts.createSourceFile("block.tsx", b.code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    return source.statements.filter(ts.isImportDeclaration).map((node) => ({
      entry: node.moduleSpecifier.text,
      names:
        node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings)
          ? node.importClause.namedBindings.elements.map((e) => (e.propertyName ?? e.name).text)
          : [],
    }));
  });
  return blocks.map((b) => {
    const metadata = b.info.join(" ");
    const fragment = /(?:^|\s)fragment(?=:|\s|$)/.test(metadata);
    const reason = /(?:^|\s)fragment:\s*(.*)$/.exec(metadata)?.[1].trim();
    const preludeNames = /(?:^|\s)prelude=([^\s]+)/.exec(metadata)?.[1].split(",") ?? [];
    return { file, line: b.line, lang: b.lang, code: b.code, fragment, reason, preludeNames, pageImports };
  });
}

/** Invalid opt-outs are errors even though the block itself is not compiled. */
export function markerProblems(blocks) {
  return blocks
    .filter((b) => b.fragment && !b.reason)
    .map((b) => ({
      file: b.file,
      line: b.line - 1,
      message: "fragment requires a reason: use fragment: <reason>",
      code: "marker",
      block: b,
    }));
}

/** Index names through the declaration checker, following aliases and export-star barrels. */
export function exportIndex(paths) {
  const program = ts.createProgram(Object.values(paths).flat(), {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.Preserve,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    paths,
    skipLibCheck: true,
    types: [],
  });
  const checker = program.getTypeChecker();
  const names = new Map();
  for (const [entry, [file]] of Object.entries(paths)) {
    const source = program.getSourceFile(file);
    const symbol = source && checker.getSymbolAtLocation(source);
    if (!symbol) continue;
    for (const exported of checker.getExportsOfModule(symbol)) {
      if (exported.name === "default") continue;
      const entries = names.get(exported.name) ?? [];
      entries.push(entry);
      names.set(exported.name, entries);
    }
  }
  return names;
}

function preferredEntry(name, entries, imports = []) {
  return (
    imports.find((i) => entries.includes(i.entry) && i.names.includes(name))?.entry ??
    imports.find((i) => entries.includes(i.entry))?.entry ??
    entries.find((entry) => entry.split("/").length === 2) ??
    [...entries].sort()[0]
  );
}

