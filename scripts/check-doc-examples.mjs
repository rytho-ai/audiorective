// Type-checks every ts/js code block of the consumer docs against the built packages (`packages/*/dist`), the way an installed consumer sees them.
// A block is wrapped as its own module, `@audiorective/*` entries resolve to dist through a generated tsconfig `paths`, and `tsc --strict` runs over all of them.
// Missing names receive public imports or typed placeholders from PRELUDE. Use prelude=name or prelude=name:Type (PRELUDE_TYPES) for ambiguous names.
// Only deliberately incomplete blocks opt out with ```ts fragment: <reason>; a bare fragment marker fails the gate.
