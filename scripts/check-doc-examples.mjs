function declarations(prelude) {
  const source = ts.createSourceFile("prelude.d.ts", prelude, ts.ScriptTarget.Latest, true);
  return new Map(
    source.statements
      .filter(ts.isVariableStatement)
      .flatMap((s) => s.declarationList.declarations.map((d) => [d.name.getText(source), d.type.getText(source)])),
  );
}

/** `paths` mapping every `@audiorective/*` entry (and its package root) to its built declaration. */
export function dist(base = root) {
  const paths = {};
  const packages = join(base, "packages");
  for (const name of readdirSync(packages)) {
    const dir = join(packages, name);
    if (!existsSync(join(dir, "package.json"))) continue;
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    if (!pkg.name?.startsWith("@audiorective/")) continue;
    for (const { entry, file } of packageEntries(dir)) {
      const specifier = entry === "." ? pkg.name : `${pkg.name}/${entry.slice(2)}`;
      if (!file) throw new Error(`build the packages first (pnpm build); missing dist declaration for ${specifier}`);
      paths[specifier] = [file];
    }
  }
  return paths;
}

/**
 * Writes one module per block under `out` and returns the generated tsconfig path plus a map from generated file to block.
 * `modules` resolves bare imports (react, three…) from the directories that hold them.
 */
export function generate(blocks, out, base = root, prelude = PRELUDE) {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const files = new Map();
  const paths = dist(base);
  const index = exportIndex(paths);
  const placeholders = declarations(prelude);
  blocks.forEach((block, i) => {
    const jsx = block.lang === "tsx" || block.lang === "jsx";
    const js = block.lang === "js" || block.lang === "javascript" || block.lang === "jsx" || block.lang === "mjs";
    const ext = js ? (jsx ? "jsx" : "js") : jsx ? "tsx" : "ts";
    const name = `block-${String(i).padStart(4, "0")}.${ext}`;
    const code = `${block.code}\nexport {};`;
    writeFileSync(join(out, name), code);
    files.set(join(out, name), block);
  });

  // Third-party packages the docs import (react, three, playcanvas, pixi.js, alien-signals): link them from the web app, which installs all of them.
  const vendor = join(out, "node_modules");
  mkdirSync(join(vendor, "@types"), { recursive: true });
  const web = join(base, "apps/web/node_modules");
  for (const name of [
    "react",
    "react-dom",
    "three",
    "playcanvas",
    "pixi.js",
    "alien-signals",
    "@types/react",
    "@types/react-dom",
    "@types/three",
    "@types/node",
  ]) {
    const from = [join(web, name), join(base, "packages/core/node_modules", name)].find(existsSync);
    if (from) symlinkSync(realpathSync(from), join(vendor, name));
  }
  const tsconfig = {
    compilerOptions: {
      strict: true,
      noEmit: true,
      noUncheckedSideEffectImports: true,
      target: "esnext",
      lib: ["esnext", "dom", "dom.iterable"],
      module: "preserve",
      moduleResolution: "bundler",
      jsx: "react-jsx",
      allowJs: true,
      checkJs: true,
      skipLibCheck: true,
      types: existsSync(join(vendor, "@types/node")) ? ["node"] : [],
      typeRoots: [join(vendor, "@types")],
      baseUrl: ".",
      paths,
    },
    include: ["./*"],
  };
  writeFileSync(join(out, "tsconfig.json"), JSON.stringify(tsconfig, null, 2));
  const config = join(out, "tsconfig.json");
  const parsed = ts.parseJsonConfigFileContent(tsconfig, ts.sys, out);
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  for (const [file, block] of files) {
    const source = program.getSourceFile(file);
    const missing = new Set(
      program
        .getSemanticDiagnostics(source)
        .filter((d) => [2304, 2552, 18004, 2503].includes(d.code))
        .map((d) => source.text.slice(d.start).match(/^[\w$]+/)?.[0])
        .filter(Boolean),
    );
    const declared = new Set();
    const binding = (node) => {
      if (ts.isIdentifier(node)) declared.add(node.text);
      else if (ts.isObjectBindingPattern(node) || ts.isArrayBindingPattern(node)) {
        for (const element of node.elements) if (ts.isBindingElement(element)) binding(element.name);
      }
    };
    const visit = (node) => {
      if (
        ts.isVariableDeclaration(node) ||
        ts.isParameter(node) ||
        ts.isFunctionDeclaration(node) ||
        ts.isClassDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isEnumDeclaration(node) ||
        ts.isTypeParameterDeclaration(node) ||
        ts.isImportClause(node) ||
        ts.isImportSpecifier(node) ||
        ts.isNamespaceImport(node) ||
        ts.isImportEqualsDeclaration(node)
      ) {
        if (node.name) binding(node.name);
      }
      if (
        node === source ||
        ts.isVariableStatement(node) ||
        ts.isVariableDeclarationList(node) ||
        ts.isImportDeclaration(node) ||
        ts.isImportClause(node) ||
        ts.isNamedImports(node)
      )
        ts.forEachChild(node, visit);
    };
    visit(source);
    const overrides = new Map();
    for (const spec of block.preludeNames ?? []) {
      const [name, type] = spec.split(":");
      if (!placeholders.has(name) || (type && !PRELUDE_TYPES[type])) {
        throw new Error(`${block.file}:${block.line - 1}: unknown prelude selection '${spec}'`);
      }
      overrides.set(name, type ? PRELUDE_TYPES[type] : placeholders.get(name));
    }
    for (const name of overrides.keys()) missing.add(name);
    const prefix = [];
    const js = /\.(?:jsx?|mjs)$/.test(file);
    for (const name of missing) {
      if (declared.has(name)) continue;
      const entries = index.get(name);
      if (entries && !overrides.has(name)) {
        prefix.push(`import { ${name} } from "${preferredEntry(name, entries, block.pageImports)}";`);
      } else if (overrides.has(name) || placeholders.has(name)) {
        const type = overrides.get(name) ?? placeholders.get(name);
        prefix.push(
          js ? `/** @type {${type}} */ const ${name} = /** @type {${type}} */ (/** @type {unknown} */ (null));` : `declare const ${name}: ${type};`,
        );
      }
    }
    // Store generated offsets separately: diagnostics always point back to the original Markdown line.
    files.set(file, { ...block, offset: prefix.length });
    writeFileSync(file, [...prefix, block.code, "export {};"].join("\n"));
  }
  return { tsconfig: config, files };
}

/** Type-check the generated project; returns `{ file, line, message, code }` per diagnostic, with `line` in the markdown file. */
export function check(tsconfigPath, files) {
  const read = ts.readConfigFile(tsconfigPath, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, dirname(tsconfigPath));
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const out = [];
  for (const d of ts.getPreEmitDiagnostics(program)) {
    const block = d.file ? files.get(resolve(d.file.fileName)) : undefined;
    const message = ts.flattenDiagnosticMessageText(d.messageText, "\n").split("\n")[0];
    if (!block) {
      if (d.file && d.file.fileName.includes("prelude")) out.push({ file: "prelude", line: 0, message, code: d.code });
      else if (!d.file) out.push({ file: "tsconfig", line: 0, message, code: d.code });
      continue;
    }
    const at = d.file.getLineAndCharacterOfPosition(d.start ?? 0).line;
    out.push({ file: block.file, line: block.line + at - (block.offset ?? 0), message, code: d.code, block });
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const exclude = process.argv
    .slice(2)
    .filter((a) => a.startsWith("--exclude="))
    .map((a) => a.slice(10));
  const files = docFiles().filter((f) => !exclude.includes(rel(f)));
  const blocks = files.flatMap((f) => exampleBlocks(rel(f), read(f)));
  const checked = blocks.filter((b) => !b.fragment);
  const out = join(root, "node_modules", ".cache", "doc-examples");
  try {
    if (!Object.keys(dist()).length) throw new Error("build the packages first (pnpm build); no dist declarations found");
  } catch (error) {
    console.error(`check:doc-examples: ${error.message}`);
    process.exit(1);
  }
  const gen = generate(checked, out);
  const problems = [...markerProblems(blocks), ...check(gen.tsconfig, gen.files)];
  // The first diagnostic per block is the one to read; the rest are usually consequences.
  const seen = new Set();
  for (const p of problems) {
    const key = `${p.file}:${p.line}:${p.message}`;
    if (seen.has(key)) continue;
    seen.add(key);
    console.error(`${p.file}:${p.line}: ${typeof p.code === "number" ? `TS${p.code} ` : ""}${p.message}`);
  }
  const bad = new Set(problems.map((p) => (p.block ? `${p.block.file}:${p.block.line}` : p.file)));
  console.log(
    `check:doc-examples: ${files.length} files, ${blocks.length} blocks: ${checked.length} checked, ${blocks.length - checked.length} marked fragment, ${bad.size} failing`,
  );
  if (problems.length) process.exit(1);
}
